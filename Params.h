// parameters that belong to the plugin, not to a stored program
static inline bool isGlobalParam (const char* id)
{
    return ! std::strcmp (id, "in") || ! std::strcmp (id, "out") || ! std::strcmp (id, "bypass") || ! std::strcmp (id, "midich") || ! std::strcmp (id, "midipc") || (id[0] == 'h' && id[1] == 'c');
}

